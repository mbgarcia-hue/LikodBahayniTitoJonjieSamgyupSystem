import { test, expect } from '@playwright/test';

for (const role of ['cashier', 'owner']) {
  test(`${role}: actual stock rejects blanks, retains failed edits and persists saved quantities`, async ({ page }) => {
    await page.goto(`/${role}/login`);
    await page.getByLabel('Username', { exact: true }).fill(role);
    await page.getByLabel('Password', { exact: true }).fill(`${role[0].toUpperCase()}${role.slice(1)}@123`);
    await page.getByRole('button', { name: 'Sign in', exact: true }).click();
    await expect(page).toHaveURL(role === 'cashier' ? /\/cashier\/billing$/ : /\/owner$/);
    await page.goto(role === 'cashier' ? '/cashier/inventory' : '/admin/inventory');
    const row = page.getByRole('row').filter({ has: page.getByRole('cell', { name: 'Rice', exact: true }) });
    const original = (await (await page.request.get('/api/dining/state')).json()).inventory.find(i => i.id === 'inv-7').currentStock;
    await row.getByRole('button', { name: 'Edit', exact: true }).click();
    const input = page.getByLabel('Available stock for Rice', { exact: true });
    let writes = 0;
    page.on('request', request => { if (request.method() === 'PATCH' && request.url().endsWith('/inventory/inv-7')) writes++; });
    await input.fill('');
    await row.getByRole('button', { name: 'Save', exact: true }).click();
    await expect(page.getByText('Enter a stock quantity of zero or more.', { exact: true })).toBeVisible();
    expect(writes).toBe(0);
    await input.fill('-1');
    await row.getByRole('button', { name: 'Save', exact: true }).click();
    expect(writes).toBe(0);
    await page.route('**/api/dining/inventory/inv-7', route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: 'Stock service unavailable' }) }));
    await input.fill('12.375');
    await row.getByRole('button', { name: 'Save', exact: true }).click();
    await expect(page.getByText('Stock service unavailable', { exact: true })).toBeVisible();
    await expect(input).toHaveValue('12.375');
    expect((await (await page.request.get('/api/dining/state')).json()).inventory.find(i => i.id === 'inv-7').currentStock).toBe(original);
    await page.unroute('**/api/dining/inventory/inv-7');
    await row.getByRole('button', { name: 'Save', exact: true }).click();
    await expect(page.getByText('Stock saved.', { exact: true })).toBeVisible();
    await page.reload();
    await expect(row.getByRole('cell', { name: '12.375', exact: true })).toBeVisible();
    expect((await (await page.request.get('/api/dining/state')).json()).inventory.find(i => i.id === 'inv-7').currentStock).toBe(12.375);
    // Explicit zero is a valid count; restore afterwards so other flow tests keep their stock.
    await row.getByRole('button', { name: 'Edit', exact: true }).click();
    await input.fill('0');
    await row.getByRole('button', { name: 'Save', exact: true }).click();
    await expect(row.getByRole('cell', { name: 'Out of Stock', exact: true })).toBeVisible();
    expect((await page.request.patch('/api/dining/inventory/inv-7', { data: { currentStock: original } })).ok()).toBe(true);
  });
}

test('cashier adds a product and hides or restores it on a customer menu without losing submitted history', async ({ browser }) => {
  test.setTimeout(90000);
  const staff = await browser.newContext(), customer = await browser.newContext();
  try {
    const cashier = await staff.newPage();
    await cashier.goto('/cashier/login');
    await cashier.getByLabel('Username', { exact: true }).fill('cashier');
    await cashier.getByLabel('Password', { exact: true }).fill('Cashier@123');
    await cashier.getByRole('button', { name: 'Sign in', exact: true }).click();
    await expect(cashier).toHaveURL(/\/cashier\/billing$/);
    const visit = await (await staff.request.post('/api/dining/open', { data: { tableNumber: 10, regularPax: 1, discountedPax: 0 } })).json();
    await cashier.goto('/cashier/inventory');
    await cashier.getByRole('button', { name: 'Add product', exact: true }).click();
    await cashier.getByLabel('Product name', { exact: true }).fill('Mango Shake');
    await cashier.getByLabel('Menu category', { exact: true }).fill('Drinks');
    await cashier.getByLabel('Price per order (₱)', { exact: true }).fill('65');
    await cashier.getByLabel('Stock unit', { exact: true }).fill('liters');
    await cashier.getByLabel('Opening stock', { exact: true }).fill('3.5');
    await cashier.getByLabel('Low stock threshold', { exact: true }).fill('1');
    await cashier.getByLabel('Stock used per order').fill('0.25');
    await cashier.getByLabel('Description (optional)').fill('Fresh mango shake');
    await cashier.locator('#add-product-form').screenshot({ path: 'test-results/inventory-product-form.png' });
    await cashier.route('**/api/dining/inventory', route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: 'Product service unavailable' }) }));
    await cashier.getByRole('button', { name: 'Save product', exact: true }).click();
    await expect(cashier.getByText('Product service unavailable', { exact: true })).toBeVisible();
    await expect(cashier.getByLabel('Product name', { exact: true })).toHaveValue('Mango Shake');
    await cashier.unroute('**/api/dining/inventory');
    const created = cashier.waitForResponse(response => response.url().endsWith('/api/dining/inventory') && response.request().method() === 'POST');
    await cashier.getByRole('button', { name: 'Save product', exact: true }).click();
    const product = await (await created).json();
    await expect(cashier.getByText('Product added to inventory and menu.', { exact: true })).toBeVisible();
    const row = cashier.getByRole('row').filter({ has: cashier.getByRole('cell', { name: 'Mango Shake', exact: true }) });
    await expect(row.getByRole('cell', { name: '3.5', exact: true })).toBeVisible();
    await cashier.reload();
    await expect(row).toBeVisible();
    const phone = await customer.newPage();
    await phone.goto('/customer/10');
    await phone.getByLabel('Visit code').fill(visit.code);
    await phone.getByRole('button', { name: 'Open menu', exact: true }).click();
    await expect(phone.getByRole('heading', { name: 'Mango Shake', exact: true })).toBeVisible();
    await phone.getByRole('button', { name: 'Add Mango Shake to batch', exact: true }).click();
    await phone.getByRole('button', { name: 'Your cart (1)', exact: true }).click();
    await phone.getByRole('button', { name: 'Submit batch', exact: true }).click();
    await expect(phone.getByRole('heading', { name: 'Shared order history', exact: true })).toBeVisible();
    await phone.getByRole('button', { name: 'Menu', exact: true }).click();
    await phone.getByRole('button', { name: 'Drinks', exact: true }).click();
    await phone.getByRole('button', { name: 'Add Mango Shake to batch', exact: true }).click();
    await row.getByRole('button', { name: 'Hide Mango Shake from customer menu', exact: true }).click();
    await expect(row.getByRole('button', { name: 'Show Mango Shake on customer menu', exact: true })).toBeVisible();
    await expect(phone.getByRole('heading', { name: 'Mango Shake', exact: true })).toHaveCount(0);
    await expect(phone.getByText('Some items were removed from your draft because they are no longer on the menu. Please review your cart.', { exact: true })).toBeVisible();
    await expect(phone.getByRole('button', { name: 'Your cart (0)', exact: true })).toBeVisible();
    await expect(phone.getByRole('button', { name: 'Add Coke to batch', exact: true })).toBeVisible();
    const access = await phone.evaluate(() => JSON.parse(localStorage.getItem('visit-10')!));
    const stale = await customer.request.post(`/api/dining/visits/${access.id}/orders`, { headers: { 'X-Visit-Token': access.token }, data: { requestId: 'hidden-draft-test', items: [{ menuItemId: product.menu.id, quantity: 1 }] } });
    expect(stale.status()).toBe(400);
    await phone.getByRole('button', { name: 'Table orders & bill', exact: true }).click();
    await expect(phone.getByText('1 × Mango Shake — ₱65', { exact: true })).toBeVisible();
    const saved = await (await staff.request.get('/api/dining/state')).json();
    expect(saved.inventory.find(i => i.id === product.inventory.id).currentStock).toBe(3.25);
    expect(saved.orders.filter(o => o.sessionId === visit.id)).toHaveLength(1);
    await cashier.reload();
    await row.getByRole('button', { name: 'Show Mango Shake on customer menu', exact: true }).click();
    await phone.getByRole('button', { name: 'Menu', exact: true }).click();
    await expect(phone.getByRole('heading', { name: 'Mango Shake', exact: true })).toBeVisible();
    const coke = cashier.getByRole('row').filter({ has: cashier.getByRole('cell', { name: 'Coke', exact: true }) });
    await expect(phone.getByRole('heading', { name: 'Coke', exact: true })).toBeVisible();
    await coke.getByRole('button', { name: 'Hide Coke from customer menu', exact: true }).click();
    await expect(phone.getByRole('heading', { name: 'Coke', exact: true })).toHaveCount(0);
    await coke.getByRole('button', { name: 'Show Coke on customer menu', exact: true }).click();
    await expect(phone.getByRole('heading', { name: 'Coke', exact: true })).toBeVisible();
  } finally { await Promise.all([staff.close(), customer.close()]); }
});
