import { test, expect } from '@playwright/test';

test('cashier expands the floor with a unique QR and safely hides or restores table cards', async ({ browser }) => {
  test.setTimeout(90000);
  const staff = await browser.newContext(), customer = await browser.newContext(), kitchen = await browser.newContext();
  try {
    const cashier = await staff.newPage();
    await cashier.setViewportSize({ width: 1280, height: 1100 });
    await cashier.goto('/cashier/login');
    await cashier.getByLabel('Username', { exact: true }).fill('cashier');
    await cashier.getByLabel('Password', { exact: true }).fill('Cashier@123');
    await cashier.getByRole('button', { name: 'Sign in', exact: true }).click();
    await expect(cashier).toHaveURL(/\/cashier\/billing$/);
    const before = await (await staff.request.get('/api/dining/state')).json();
    const visibleCount = before.tables.filter(t => !t.hidden).length;
    await cashier.route('**/api/dining/tables', route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: 'Unable to add table right now' }) }));
    await cashier.getByRole('button', { name: 'Add table', exact: true }).click();
    await expect(cashier.getByText('Unable to add table right now', { exact: true })).toBeVisible();
    expect((await (await staff.request.get('/api/dining/state')).json()).tables).toHaveLength(before.tables.length);
    await cashier.unroute('**/api/dining/tables');
    const created = cashier.waitForResponse(r => r.url().endsWith('/api/dining/tables') && r.request().method() === 'POST');
    await cashier.getByRole('button', { name: 'Add table', exact: true }).click();
    const table = await (await created).json(); expect(table.id).toBeGreaterThan(10);
    const card = cashier.locator(`.qr-print [data-table-id="${table.id}"]`);
    await expect(card.getByRole('heading', { name: `Table ${table.id}`, exact: true })).toBeVisible();
    const link = await card.getByRole('link', { name: 'Open customer page ↗', exact: true }).getAttribute('href');
    expect(link).toBe(`http://127.0.0.1:3107/customer/${table.id}`);
    const qr = card.getByRole('img'); await expect(qr).toBeVisible();
    const qrSource = await qr.getAttribute('src'); expect(qrSource).toMatch(/^data:image\/png;base64,/);
    expect(qrSource).not.toBe(await cashier.locator('.qr-print [data-table-id="1"] img').getAttribute('src'));
    await expect(cashier.getByRole('button', { name: `Print ${visibleCount + 1} QR codes`, exact: true })).toBeVisible();
    await card.getByRole('button', { name: `Hide Table ${table.id}`, exact: true }).click();
    await expect(card).toHaveCount(0);
    await expect(cashier.getByRole('button', { name: `Print ${visibleCount} QR codes`, exact: true })).toBeVisible();
    const phone = await customer.newPage(); await phone.goto(link!);
    await expect(phone.getByRole('heading', { name: 'Table unavailable', exact: true })).toBeVisible();
    await expect(phone.getByLabel('Visit code')).toHaveCount(0);
    await cashier.reload();
    const hiddenSection = cashier.locator('details').filter({ has: cashier.locator(':scope > summary').filter({ hasText: /^Hidden tables \(/ }) }).first();
    await hiddenSection.locator(':scope > summary').click();
    const hidden = hiddenSection.locator(`[data-table-id="${table.id}"]`);
    await expect(hidden).toBeVisible();
    // Hidden cards never enter the printable QR container, even when expanded.
    await cashier.emulateMedia({ media: 'print' });
    await expect(hidden).toHaveCSS('visibility', 'hidden');
    await cashier.emulateMedia({ media: 'screen' });
    await hidden.getByRole('button', { name: `Show Table ${table.id}`, exact: true }).click();
    await expect(card).toBeVisible();
    await expect(card.getByRole('img')).toHaveAttribute('src', qrSource!);
    await card.screenshot({ path: 'test-results/expanded-table-card.png' });
    await card.getByRole('button', { name: 'Open dining session', exact: true }).click();
    await expect(card.getByText('Visit code:')).toBeVisible();
    await expect(card.getByRole('button', { name: `Hide Table ${table.id}`, exact: true })).toBeDisabled();
    const code = (await card.locator('strong.success').innerText()).trim();
    await phone.getByRole('button', { name: 'Try again', exact: true }).click();
    await phone.getByLabel('Visit code').fill(code);
    await phone.getByRole('button', { name: 'Open menu', exact: true }).click();
    await expect(phone.getByRole('button', { name: 'Add Coke to batch', exact: true })).toBeVisible();
    await phone.getByRole('button', { name: 'Add Coke to batch', exact: true }).click();
    await phone.getByRole('button', { name: 'Your cart (1)', exact: true }).click();
    const submitted = phone.waitForResponse(r => r.url().endsWith('/orders') && r.request().method() === 'POST');
    await phone.getByRole('button', { name: 'Submit batch', exact: true }).click();
    const batch = await (await submitted).json(); expect(batch.tableNumber).toBe(table.id);
    const review = card.locator(`[data-batch-id="${batch.id}"]`);
    await review.getByRole('button', { name: 'Approve & send to kitchen', exact: true }).click();
    expect((await kitchen.request.post('/api/staff/login', { data: { username: 'kitchen', password: 'Kitchen@123', role: 'kitchen' } })).ok()).toBe(true);
    for (const status of ['preparing', 'ready']) expect((await kitchen.request.patch(`/api/dining/orders/${batch.id}`, { data: { status } })).ok()).toBe(true);
    await review.getByRole('button', { name: 'Confirm delivered & mark served', exact: true }).click();
    await phone.getByRole('button', { name: 'Finish ordering & request bill', exact: true }).click();
    await expect(card.getByRole('button', { name: `Hide Table ${table.id}`, exact: true })).toBeDisabled();
    await card.getByLabel('Cash received', { exact: true }).fill('300');
    await card.getByRole('button', { name: 'Confirm payment & close visit', exact: true }).click();
    await expect(phone.getByRole('heading', { name: 'Thank you for dining with us', exact: true })).toBeVisible();
    await expect(card.getByRole('button', { name: `Hide Table ${table.id}`, exact: true })).toBeEnabled();
    await card.getByRole('button', { name: `Hide Table ${table.id}`, exact: true }).click();
    await expect(card).toHaveCount(0);
    const saved = await (await staff.request.get('/api/dining/state')).json();
    expect(saved.transactions.find(t => t.sessionId === batch.sessionId).totalBill).toBe(255);
    expect(saved.orders.find(o => o.id === batch.id).status).toBe('served');
    await hidden.getByRole('button', { name: `Show Table ${table.id}`, exact: true }).click();
    await expect(card.getByRole('img')).toHaveAttribute('src', qrSource!);
  } finally { await Promise.all([staff.close(), customer.close(), kitchen.close()]); }
});

test('customer table lookup handles nonexistent tables and recovers from a connection error', async ({ page }) => {
  await page.goto('/customer/999999');
  await expect(page.getByRole('heading', { name: 'Table unavailable', exact: true })).toBeVisible();
  await page.route('**/api/dining/tables/1', route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: 'Restaurant connection unavailable' }) }));
  await page.goto('/customer/1');
  await expect(page.getByRole('heading', { name: 'Unable to check this table', exact: true })).toBeVisible();
  await page.unroute('**/api/dining/tables/1');
  await page.getByRole('button', { name: 'Try again', exact: true }).click();
  await expect(page.getByLabel('Visit code')).toBeVisible();
});
